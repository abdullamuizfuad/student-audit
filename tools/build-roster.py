#!/usr/bin/env python3
"""
Build roster.js: the list of student IDs allowed to sign in.

Only scrambled IDs (SHA-256 hashes) go into roster.js, never names or readable IDs,
so the class list itself is never published.

Usage (run from the student-audit folder):
    python3 tools/build-roster.py ~/Downloads/ClassList_MKT303.xls

Accepts:
  - MNU class list downloads (ClassList_*.xls, which are HTML tables). Students marked "Drop" are left out.
  - CSV files with student IDs in the first column (S0 + 5 digits).
Never commit the class list files (the repo is public). Commit and push roster.js only. Run it again whenever the class list changes, or each new term.
"""
import csv, hashlib, json, re, sys
from html.parser import HTMLParser
from pathlib import Path

TERM = "T2 2026"                      # change each term
SALT = "mkt303|" + TERM               # mixed into every hash; changes each term
ALWAYS = ["S000001"]                  # lecturer test ID
ID = re.compile(r"^S0\d{5}$")


class Table(HTMLParser):
    def __init__(self):
        super().__init__(); self.rows, self.row, self.cell = [], None, None
    def handle_starttag(self, tag, attrs):
        if tag == "tr": self.row = []
        if tag in ("td", "th"): self.cell = ""
    def handle_endtag(self, tag):
        if tag in ("td", "th") and self.row is not None:
            self.row.append(" ".join((self.cell or "").split())); self.cell = None
        if tag == "tr" and self.row is not None:
            self.rows.append(self.row); self.row = None
    def handle_data(self, data):
        if self.cell is not None: self.cell += data


def ids_from_classlist(path):
    t = Table(); t.feed(Path(path).read_text(encoding="utf-8", errors="replace"))
    head = [h.lower() for h in t.rows[0]]
    mail, status = head.index("e-mail address"), head.index("status")
    active, dropped = set(), set()
    for r in t.rows[1:]:
        if len(r) <= max(mail, status): continue
        sid = r[mail].split("@")[0].upper()     # the ID column is an internal number; the email holds the student ID
        if ID.match(sid): (dropped if r[status].lower() == "drop" else active).add(sid)
    return active, dropped


def ids_from_csv(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        return {row[0].strip().upper() for row in csv.reader(f) if row and ID.match(row[0].strip().upper())}, set()


def main(files):
    if not files: sys.exit(__doc__)
    active, dropped = set(ALWAYS), set()
    for f in files:
        a, d = ids_from_csv(f) if f.lower().endswith(".csv") else ids_from_classlist(f)
        active |= a; dropped |= d
        print(f"{Path(f).name}: {len(a)} active, {len(d)} dropped")
    dropped -= active                     # a student who moved section stays in
    hashes = sorted(hashlib.sha256((SALT + "|" + s).encode()).hexdigest() for s in active)
    out = Path(__file__).resolve().parent.parent / "roster.js"
    out.write_text("/* Generated by tools/build-roster.py. Scrambled student IDs only: no names, no readable IDs. */\n"
                   f"const ROSTER={json.dumps({'term': TERM, 'salt': SALT, 'hashes': hashes})};\n", encoding="utf-8")
    print(f"roster.js: {len(hashes)} IDs allowed (including lecturer test ID), {len(dropped)} dropped left out")


if __name__ == "__main__":
    main(sys.argv[1:])
